-- Snowflake external-catalog Iceberg tables
--
-- Source: Snowflake Postgres + pg_lake
-- Catalog integration: PG_LAKE_POSTGRES_CATALOG
--
-- These tables reference existing Apache Iceberg tables.
-- They do not copy data into ordinary Snowflake tables.
--
-- Prerequisite:
--   01_catalog_integration.sql

CREATE DATABASE IF NOT EXISTS PG_LAKE_ANALYTICS;

CREATE SCHEMA IF NOT EXISTS PG_LAKE_ANALYTICS.PUBLIC;

-- 1. Stores
CREATE OR REPLACE ICEBERG TABLE PG_LAKE_ANALYTICS.PUBLIC.ICEBERG_STORES
    CATALOG = 'PG_LAKE_POSTGRES_CATALOG'
    CATALOG_TABLE_NAME = 'iceberg_stores'
    AUTO_REFRESH = TRUE;

-- 2. Products
CREATE OR REPLACE ICEBERG TABLE PG_LAKE_ANALYTICS.PUBLIC.ICEBERG_PRODUCTS
    CATALOG = 'PG_LAKE_POSTGRES_CATALOG'
    CATALOG_TABLE_NAME = 'iceberg_products'
    AUTO_REFRESH = TRUE;

-- 3. Customers
CREATE OR REPLACE ICEBERG TABLE PG_LAKE_ANALYTICS.PUBLIC.ICEBERG_CUSTOMERS
    CATALOG = 'PG_LAKE_POSTGRES_CATALOG'
    CATALOG_TABLE_NAME = 'iceberg_customers'
    AUTO_REFRESH = TRUE;

-- 4. Transactions
CREATE OR REPLACE ICEBERG TABLE PG_LAKE_ANALYTICS.PUBLIC.ICEBERG_TRANSACTIONS
    CATALOG = 'PG_LAKE_POSTGRES_CATALOG'
    CATALOG_TABLE_NAME = 'iceberg_transactions'
    AUTO_REFRESH = TRUE;

-- 5. Transaction Items
CREATE OR REPLACE ICEBERG TABLE PG_LAKE_ANALYTICS.PUBLIC.ICEBERG_TRANSACTION_ITEMS
    CATALOG = 'PG_LAKE_POSTGRES_CATALOG'
    CATALOG_TABLE_NAME = 'iceberg_transaction_items'
    AUTO_REFRESH = TRUE;
